#ifndef __MQTT_APP_H
#define __MQTT_APP_H

#include <stdint.h>

/*============================================================================
 * mqtt_app —— 中控的 MQTT 上云应用层（巴法云）
 *
 * 数据流向：
 *   终端板 --LoRa--> 中控 g_lora_rx_frame --MQTT--> 巴法云 --推送--> 手机小程序
 *
 * 三层分工（改代码前先分清楚改哪一层）：
 *   esp.c        ESP8266 的 AT 指令 + TCP 透传：只管把一串字节塞进 TCP，不懂 MQTT
 *   mqtt.c       MQTT 3.1.1 报文组包/解包：只管字节格式，不碰硬件也不管业务
 *   mqtt_app.c   本层：什么时候连、连上发什么、发到哪个主题
 *
 * ⚠ 原来放在 app_main 里的 mqtt_demo() 是**原厂示例**，函数体里是 while(1)
 *   死循环，挂在主循环里会让 LoRa 接收和 OLED 一行都执行不到。
 *   现在换成非阻塞的 MQTT_AppService()，mqtt_demo.c 已从 Keil 工程移出。
 *
 * 五个主题（**要和巴法云控制台里的主题名逐字相同，区分大小写**）：
 *   主题名        昵称        发上去的内容        例
 *   Humidity      空气湿度    #<湿度 %RH>         #61
 *   Temperature   气温        #<温度 ℃>           #29.0
 *   light         光照强度    #<光照 lux>         #124
 *   soil          soil湿度    #<土壤等级 1~4>     #1
 *   co2           co2浓度     #<CO2 ppm>          #720
 *
 *   「#」是巴法云的多数值分隔符（沿用小米格式）：第一个 # 前面是空的占位，
 *   小程序按 # 切分取值，所以**井号不能省**，单值也要写。
 *
 *   ⚠ 主题名是**全局**的：巴法云按主题名分发，不按账号隔离。light / soil / co2 /
 *     Humidity / Temperature 都是很大路的名字，别人往同名主题发的东西会一起显示在
 *     你的控制台上（你发的别人也收得到）。控制台上「订阅者：在线 N」如果比自己的
 *     设备数多，就是有别人在订阅同名主题。要避开就换成带自己前缀的主题名，
 *     注意控制台和这里的宏两边必须改一致。
 *
 *   温湿度是终端同一个 DHT22 的读数，**要么一起有效、要么一起失效**：
 *   终端没读到时温度填 LORA_TEMP_INVALID、湿度那个字节还是初值 0，
 *   所以这两项都只判温度这一个哨兵值，失效时一起发 "--"。
 *   CO2 单独看它自己的 LORA_CO2_INVALID。
 *==========================================================================*/

/*--------------------------------------------------------------------------
 * 巴法云账号私钥 —— 具体值放在同目录的 wifi_config.h（**不进公开仓库**）
 *
 *   ⚠ 私钥的作用是标识设备身份：控制台的设备管理、消息推送/联动按它认设备。
 *     但它**不决定能不能收到数据** —— 巴法云按主题名分发（见上面那条警告），
 *     换一串私钥照样能收到同名主题的消息。所以排查「控制台收不到数据」时
 *     不要往私钥上想，先看主题名对不对、有没有订阅上。
 *------------------------------------------------------------------------*/
#include "wifi_config.h" // MQTT_CLIENT_ID 在这里面

/* 五个主题名。顺序和控制台上的卡片一致 —— 增删主题只改这一块，
 * mqtt_app.c 里订阅/发布/收下行全是照着这张表遍历的。 */
#define MQTT_TOPIC_HUMI "Humidity"
#define MQTT_TOPIC_TEMP "Temperature"
#define MQTT_TOPIC_LIGHT "light"
#define MQTT_TOPIC_SOIL "soil"
#define MQTT_TOPIC_CO2 "co2"

/*--------------------------------------------------------------------------
 * 上云周期（毫秒）
 *   2500 = 收到终端一包就发一包（终端上报周期就是 2.5s）
 *   5000 = 每 5 秒发一次，发的是「此刻最近收到的那一包」
 *   终端 2.5s 一包、这里 5s 一发的意思是：中间那包会被跳过，只发最新的。
 *------------------------------------------------------------------------*/
#define MQTT_PUBLISH_PERIOD_MS 5000U

/*--------------------------------------------------------------------------
 * 心跳周期（毫秒）
 *   必须**小于**连接报文里写的 keep-alive(60s)，否则服务器先判掉线。
 *   其实我们每 5 秒就在发布消息，服务器那边的 keep-alive 计时一直在被刷新，
 *   这个心跳主要是用来「探活」：心跳失败 = 链路断了，触发整条重连。
 *------------------------------------------------------------------------*/
#define MQTT_HEART_PERIOD_MS 60000U

/* 整条链路（WiFi + TCP + MQTT）失败后的重试间隔（毫秒） */
#define MQTT_RETRY_PERIOD_MS 15000U

/*==========================================================================
 * 对外接口
 *========================================================================*/

/* 上电调用一次：只挂计时基准，不连网、不阻塞 */
void MQTT_AppInit(void);

/* 主循环里反复调用：内部自己按周期推进，除连接阶段外不阻塞 */
void MQTT_AppService(void);

#endif
