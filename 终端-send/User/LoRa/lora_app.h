#ifndef __LORA_APP_H
#define __LORA_APP_H

/*
 * ============================================================================
 * lora_app —— LoRa 应用层（终端节点）
 *
 * 硬件（终端板，LLCC68 / Ra-01SC 模块）：
 *   SPI1 : SCK=PA5  MISO=PA6  MOSI=PA7        （SPI 模式0，8bit，主机）
 *   NSS  : PA4   GPIO 输出，软件片选，空闲为高
 *   RST  : PB1   GPIO 输出，空闲为高
 *   BUSY : PB0   GPIO 输入，高=模块忙
 *   DIO1 : PB10  EXTI 上升沿 → EXTI15_10_IRQHandler → DIO1_EXTI_Callback
 *          （是上升沿：LLCC68 手册 §13.3.2.1 —— IRQ 触发时 DIO 被置位拉高，
 *            别按「按键=下降沿」的常识改回 IT_FALLING，改了就收不到中断）
 *
 *   射频参数（与 llcc68_p2p.h 里的一致）：470.5MHz / SF9 / BW125 / CR4-5
 *   空口包：前导码 8 符号，显式头，CRC 开，不反转 IQ
 *
 * 工作方式（非阻塞状态机，挂在 app_main 的 while(1) 里）：
 *   空闲 → 每 LORA_UPLOAD_PERIOD_MS 触发一次上报：
 *          进入接收窗口等网关指令 → 有指令就收下并回调处理 → 若没收到
 *          指令就发一包传感器数据 → 回到空闲
 *
 *   收发动作本身不在主循环里死等：使能收发后立刻返回，靠 DIO1 中断置的
 *   标志位推进状态。这样 OLED / CO2 / DHT22 / 光控 LED 都不被拖住。
 *   （ISR 里只置标志位，不调 printf 也不动 SPI —— 见 ISR_callback.c）
 *
 * 用法（app_main.c）：
 *   LORA_AppInit();                       // 启动时调一次
 *   while (1) { ...
 *       LORA_AppService();                // 主循环里反复调
 *   ... }
 * ============================================================================
 */

#include <stdint.h>
#include <stdbool.h>

/************************ 上传周期 ************************/
// 多久上报一次传感器数据（毫秒）。
//   这个值是「本轮开始 → 下一轮开始」的间隔，不是「发完到再发」的间隔：
//   状态机在每轮开头就把 lora_last_upload 重置了，所以一轮跑多久都不影响
//   上报周期本身 —— 只要能在一轮之内跑完就行（下面算过了，够）。
//
//   一轮最长耗时 = LORA_RX_WINDOW_MS + 本包空中时间 + LORA_ACK_WINDOW_MS
//                = 500 + 145 + 400 = 1045ms < 2500ms  ✓
//   最坏情况（DIO1 没接上，发送走 lora_app.c 里 600ms 的软件兜底）：
//                500 + 600 + 400 = 1500ms，仍然 < 2500ms  ✓
//   想改快/改慢就动这一个值，2~3 秒是比较合适的范围：
//     太快（<1100ms）：正常一轮就跑不完，状态机会自己把下一轮顺延，实际周期反而不可控
//     太慢（>5s）：中控那边 OLED 上屏的数据会明显发陈
//   2026-09-21 从 2000 调到 2500（用户要求「发送速度减 0.25」）：
//     中控每包多出 0.5 秒余量处理，ACK 和 OLED 刷新都更从容。
//   ⚠ 改这个值时要同步看一眼中控 app_main.c 的 OLED_REFRESH_PERIOD_MS，
//     它是按这个周期对齐的
#define LORA_UPLOAD_PERIOD_MS 2500

/************************ 接收窗口 ************************/
// 每次上报前，先在这个窗口内等中控下发指令（毫秒）。
//   0 = 一直挂着接收（更实时，但功耗高、且状态机会一直停在 RX）
//   非0 = 收完/超时后继续走上报流程
//   目前中控只会回 ACK、不会主动下发指令，所以这个窗口收不到东西，
//   只是白等 —— 给 500ms 让状态机有个机会响应以后要加的控制指令。
//   注意它和 LORA_ACK_WINDOW_MS 是两回事：这个是「发之前」开的。
#define LORA_RX_WINDOW_MS 500

/************************ ACK 等待窗口 ************************/
// 上报发完之后，再开这么长一个接收窗口等中控的ACK（毫秒）。0 = 不等
//   必须开在「发送之后」：中控要收到本包才会回ACK，而上面那个
//   LORA_RX_WINDOW_MS 窗口在发送之前，那时候本包还没发出去，等不到ACK
//
//   窗口从 TX_DONE（本包发完）开始算，所以里面**不包含**本包的发送时间：
//     本包空中时间约 145ms（算完就完了，不计入窗口）
//     中控收到 → 解析 → 回 ACK，ACK 空中时间约 104ms
//   也就是窗口开了之后大约 104 + (中控解析的几十毫秒) 就能收到，
//   400ms 有近 4 倍余量，不用再收紧。
//   （145 / 104 是用厂商驱动自己的 llcc68_get_lora_time_on_air_in_ms() 实算的；
//     本包从 8 字节涨到 10 字节后，空中时间从 124ms 变成 145ms）
#define LORA_ACK_WINDOW_MS 400

/************************ 帧 格 式 ************************
 * 本工程定的应用层帧格式，网关端要照这个解析/组包。
 *
 * 【上行：终端 → 网关】固定 10 字节（LORA_TX_FRAME_LEN），多字节字段一律小端
 *   下标  长度  含义          类型     说明
 *    0     1   帧头          uint8    固定 0xAA
 *    1     1   设备ID        uint8    本节点填 LORA_DEVICE_ID
 *    2     2   光照强度      int16    单位 lux，取值 0~350
 *    4     1   土壤湿度等级  uint8    1~4（1干燥 / 2微湿 / 3湿润 / 4饱和）
 *    5     2   温度          int16    单位 0.1℃，235 表示 23.5℃，可为负
 *    7     1   湿度          uint8    单位 1%RH，整数部分，0~100
 *    8     2   CO2 浓度      uint16   单位 ppm，LORA_CO2_INVALID 表示没读到
 *          —— 合计 10 字节
 *
 *   ⚠ CO2 是 2026-09-21 追加到帧尾的（原 8 字节）。
 *     追加而不是插在中间，是为了让老位置的偏移全都不变。
 *     10 字节比 8 字节多 1 个负载符号（空中时间 124ms → 145ms），对 2.5s 的周期无影响。
 *     **两端必须同步改**：中控那边 LORA_FRAME_LEN 也是 10，它按长度判帧，
 *     长度对不上会直接丢弃并打印「长度异常的包」。
 *
 * 【下行：中控/网关 → 终端】帧头 0xAA + 设备ID(1字节)，之后是自定义负载。
 *   本模块只校验「帧头 + 设备ID是不是自己」，然后把负载交给 LORA_OnRecv()。
 *   负载第1字节是指令码，目前定义了一个：
 *     LORA_CMD_ACK (0x01)：中控收到上报后的确认，整帧 3 字节
 *                          [0]=0xAA  [1]=本设备ID  [2]=0x01
 *   要加控制指令（开灯、关阀之类）就往这里继续加指令码，
 *   然后在 LORA_OnRecv() 里按指令码分发。
 *   对端（中控）工程：TMPLATE - 15.1-中控和终端\TMPLATE - 14-LORA - recv
 *                     的 User/LoRa/lora_app.h，两份帧格式必须一致
 * ========================================================== */

/************************ 下行指令码 ************************/
#define LORA_CMD_ACK 0x01 // 中控收到上报后的确认

/************************ 上行帧下标 ************************/
// 逐字节按数组拼，不用结构体，避免编译器对齐填充带来的歧义
#define LORA_TX_FRAME_LEN 10
#define LORA_TX_IDX_HEAD 0  // 帧头 0xAA
#define LORA_TX_IDX_DEVID 1 // 设备ID
#define LORA_TX_IDX_LIGHT 2 // 光照 lux      int16 小端
#define LORA_TX_IDX_SOIL 4  // 土壤湿度等级 uint8
#define LORA_TX_IDX_TEMP 5  // 温度 0.1℃    int16 小端
#define LORA_TX_IDX_HUMI 7  // 湿度 %RH     uint8
#define LORA_TX_IDX_CO2 8   // CO2 浓度 ppm  uint16 小端

// CO2 无效标记：终端没读到 CO2 传感器时填这个值。
//   不用 0 当无效：0 ppm 是物理上不可能出现的读数（大气本底约 400ppm），
//   但用显式的哨兵值和温度的 LORA_TEMP_INVALID 一个路子，读代码时更清楚。
//   中控收到这个值就把屏上 CO2 那行显示成 "---"
#define LORA_CO2_INVALID 0xFFFF

// 条件编译开关：置 1 就退回「老的 4 字节帧」（只发光照2 + 土壤2，无帧头），
// 用来兼容已经按老格式写好、暂时不想改的网关端
#define LORA_USE_LEGACY_4B_FRAME 0

/************************ 帧头与设备ID ************************/
#define LORA_FRAME_HEAD 0xAA // 上下行统一的帧头
#define LORA_DEVICE_ID 0x01  // 本终端节点地址（网关按这个区分多个节点）

/************************ 对外接口 ************************/

// 上电调用一次。内部只做必要的初始化（读一次 DHT22 引脚），
// 射频初始化放到 LORA_AppService() 里重试，失败不会卡死主循环
void LORA_AppInit(void);

// 主循环里反复调用。内部自己计时，不阻塞
void LORA_AppService(void);

// 收到网关下行的回调：payload 是完整负载（不含帧头/设备ID），len 是长度。
// 需要处理网关指令就往这里加逻辑。不实现（留空）也不会报错，
// 因为下面有 __weak 的默认空实现
void LORA_OnRecv(const uint8_t *payload, uint16_t len);

/************************ 诊断计数（调试用） ************************/
extern volatile uint32_t g_lora_tx_ok_cnt;   // 成功发出的包数
extern volatile uint32_t g_lora_tx_err_cnt;  // 发送失败/超时次数
extern volatile uint32_t g_lora_rx_ok_cnt;   // 成功收到的包数
extern volatile uint32_t g_lora_rx_err_cnt;  // 接收出错（CRC错等）次数

#endif
